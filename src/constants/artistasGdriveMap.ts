export function obterFotoRealGdrive(nome: string): string | null {
  if (!nome) return null;
  if (ARTISTAS_FOTOS_GDRIVE[nome]) return ARTISTAS_FOTOS_GDRIVE[nome];
  const lower = nome.trim().toLowerCase();
  for (const [key, url] of Object.entries(ARTISTAS_FOTOS_GDRIVE)) {
    if (key.trim().toLowerCase() === lower) return url;
  }
  return null;
}
